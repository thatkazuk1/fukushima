#!/usr/bin/env bash
# Build the self-contained GTK stylesheets and link them into ~/.config.
set -euo pipefail
cd "$(dirname "$0")"
for v in 3.0 4.0; do
  { echo "/* Generated by gtk/build.sh. Do not edit. */"; cat palette.css shape.css; } > "gtk-$v.css"
  mkdir -p "$HOME/.config/gtk-$v"
  ln -sfn "$PWD/gtk-$v.css" "$HOME/.config/gtk-$v/gtk.css"
done
echo "linked gtk-3.0 and gtk-4.0"
